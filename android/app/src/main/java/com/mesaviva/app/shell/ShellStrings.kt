    fun t(language: String, key: String, params: Map<String, Any?> = emptyMap()): String {
        val template = (if (language == "en") en[key] else es[key]) ?: es[key] ?: key
        if (params.isEmpty()) return template
        var result = template
        for ((name, value) in params) {
            result = result.replace("{$name}", value?.toString() ?: "")
        }
        return result
    }
